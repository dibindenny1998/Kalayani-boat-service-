/* Kalyani Boat Service: shared behaviour for every page.
   Tour data and contact numbers come from assets/js/data.js (generated by build/build.py).
   Motion uses GSAP + ScrollTrigger + Lenis when they load; the page works fully without them. */
(() => {
  const K = window.KALYANI;
  const still = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => [...r.querySelectorAll(s)];
  const inr = v => "₹" + v.toLocaleString("en-IN");
  const waLink = msg => "https://wa.me/" + K.whatsapp + "?text=" + encodeURIComponent(msg);
  const G = window.gsap, ST = window.ScrollTrigger;

  /* header: shadow once scrolled, full-screen mobile menu */
  const top = $(".top");
  const onScroll = () => top.classList.toggle("scrolled", scrollY > 8);
  addEventListener("scroll", onScroll, { passive: true }); onScroll();
  const menu = $(".menu"), nav = $(".nav");
  if (menu) {
    menu.onclick = () => { const o = nav.classList.toggle("open"); menu.setAttribute("aria-expanded", o); document.body.style.overflow = o ? "hidden" : ""; };
    nav.addEventListener("click", e => { if (e.target.closest("a")) { nav.classList.remove("open"); menu.setAttribute("aria-expanded", "false"); document.body.style.overflow = ""; } });
  }

  /* every [data-wa] link opens WhatsApp with its own pre-filled message */
  $$("[data-wa]").forEach(a => { a.href = waLink(a.dataset.wa || "Hi Kalyani Boat Service! I'd like to book a shikara ride."); a.target = "_blank"; a.rel = "noopener"; });

  /* smooth scrolling */
  let lenis = null;
  if (!still && window.Lenis) {
    lenis = new Lenis({ lerp: .1 });
    if (G && ST) { lenis.on("scroll", ST.update); G.ticker.add(t => lenis.raf(t * 1000)); G.ticker.lagSmoothing(0); }
    else { const raf = t => { lenis.raf(t); requestAnimationFrame(raf); }; requestAnimationFrame(raf); }
  }

  /* reveals: anything already on screen shows at once; the rest rises in as it scrolls into view */
  const rv = $$(".rv");
  if (still || !("IntersectionObserver" in window)) rv.forEach(e => e.classList.add("in"));
  else {
    const io = new IntersectionObserver(es => es.forEach(e => { if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); } }), { threshold: .12, rootMargin: "0px 0px -6% 0px" });
    rv.forEach(e => { if (e.getBoundingClientRect().top < innerHeight) e.classList.add("in"); else io.observe(e); });
  }

  /* statement: words fill with colour as you scroll through it */
  const scrub = $("#scrub");
  if (scrub) {
    scrub.innerHTML = scrub.textContent.trim().split(/\s+/).map(w => `<span class="w dim">${w}</span>`).join(" ");
    const words = $$(".w", scrub);
    const fill = () => { const r = scrub.getBoundingClientRect(), p = Math.min(1, Math.max(0, (innerHeight * .8 - r.top) / (r.height + innerHeight * .35))); const n = Math.round(p * words.length); words.forEach((w, i) => w.classList.toggle("dim", i >= n)); };
    if (still) words.forEach(w => w.classList.remove("dim")); else { addEventListener("scroll", fill, { passive: true }); fill(); }
  }

  /* route line draws down as it scrolls past */
  $$(".route").forEach(r => {
    if (still) return;
    const draw = () => { const b = r.getBoundingClientRect(); r.style.setProperty("--p", Math.min(1, Math.max(0, (innerHeight * .85 - b.top) / b.height)).toFixed(3)); };
    addEventListener("scroll", draw, { passive: true }); draw();
  });

  /* day track: on wide screens the section pins and the day slides sideways as you scroll */
  const track = $("#track");
  if (track && G && ST && !still) {
    G.registerPlugin(ST);
    const mm = G.matchMedia();
    mm.add("(min-width: 900px)", () => {
      const sec = track.closest(".day"); sec.classList.add("js-pin");
      const dist = () => Math.max(0, track.scrollWidth - innerWidth);
      const tw = G.to(track, { x: () => -dist(), ease: "none", scrollTrigger: { trigger: sec, start: "top top", end: () => "+=" + dist(), pin: true, scrub: .6, invalidateOnRefresh: true } });
      return () => { sec.classList.remove("js-pin"); tw.scrollTrigger && tw.scrollTrigger.kill(); tw.kill(); G.set(track, { x: 0 }); };
    });
    addEventListener("load", () => ST.refresh());
  }

  /* hero photos drift with the pointer */
  const floats = $$(".hero .float, .hero .badge");
  if (floats.length && !still && matchMedia("(pointer: fine)").matches) {
    addEventListener("pointermove", e => { const x = e.clientX / innerWidth - .5, y = e.clientY / innerHeight - .5;
      floats.forEach((f, i) => { const d = [22, -16, 12][i] || 10; f.style.translate = `${(x * d).toFixed(1)}px ${(y * d).toFixed(1)}px`; }); }, { passive: true });
  }

  /* price calculator: base price covers two guests; each extra guest pays a rate per hour */
  const price = (t, g) => t.price + Math.max(0, g - 2) * t.extra * t.hours;
  $$("[data-calc]").forEach(form => {
    const sel = $("[name=tour]", form), out = $("output", form), sum = $(".sum", form), note = $(".sumnote", form);
    let guests = +(out.value || 2), shown = 0, raf;
    const tour = () => K.tours.find(t => t.slug === sel.value) || K.tours[0];
    const update = () => {
      const t = tour(), v = price(t, guests), extra = Math.max(0, guests - 2);
      out.value = guests; out.textContent = guests;
      $("[name=guests]", form).value = guests;
      note.textContent = extra ? `${inr(t.price)} for two + ${extra} extra × ₹${t.extra} × ${t.hours} hrs` : "Base price, covers up to two guests";
      cancelAnimationFrame(raf);
      if (still || !shown) { shown = v; sum.textContent = inr(v); return; }
      const from = shown, st = performance.now();
      const step = n => { const k = Math.min(1, (n - st) / 600), e = 1 - Math.pow(1 - k, 3); shown = Math.round(from + (v - from) * e); sum.textContent = inr(shown); if (k < 1) raf = requestAnimationFrame(step); };
      raf = requestAnimationFrame(step);
    };
    $("[data-step='-1']", form).onclick = () => { if (guests > 1) { guests--; update(); } };
    $("[data-step='1']", form).onclick = () => { if (guests < 30) { guests++; update(); } };
    sel.addEventListener("change", update);
    const want = new URLSearchParams(location.search).get("tour");
    if (want && K.tours.some(t => t.slug === want)) sel.value = want;
    update();

    /* enquiry: send on WhatsApp, or by email through enquiry.php */
    const status = $(".status", form);
    const say = (msg, kind) => { if (!status) return; status.hidden = false; status.className = "status " + (kind || ""); status.textContent = msg; };
    const summary = () => {
      const f = new FormData(form), t = tour(), lines = [
        `Hi Kalyani Boat Service! I'd like to book: ${t.name}${t.start ? " (" + t.time + ")" : ""}.`,
        f.get("date") ? `Date: ${f.get("date")}` : "",
        f.get("start") ? `Preferred start time: ${f.get("start")}` : "",
        `Guests: ${guests}`,
        `Estimated price: ${inr(price(t, guests))}`,
        f.get("name") ? `Name: ${f.get("name")}` : "",
        f.get("phone") ? `Phone: ${f.get("phone")}` : "",
        f.get("message") ? `Note: ${f.get("message")}` : ""
      ];
      return lines.filter(Boolean).join("\n");
    };
    const waBtn = $("[data-send=wa]", form);
    if (waBtn) waBtn.onclick = () => { window.open(waLink(summary()), "_blank", "noopener"); };
    form.addEventListener("submit", async e => {
      if (!form.action || !form.matches("[data-email]")) return;
      e.preventDefault();
      if (!form.reportValidity()) return;
      const btn = $("[type=submit]", form); btn.disabled = true; say("Sending…");
      try {
        const res = await fetch(form.action, { method: "POST", body: new FormData(form), headers: { Accept: "application/json" } });
        const data = await res.json().catch(() => ({}));
        if (res.ok && data.ok) { say("Thank you! Your enquiry has been sent. We will reply on WhatsApp or phone shortly.", "ok"); form.reset(); guests = 2; update(); }
        else say(data.error || "Sorry, the enquiry could not be sent. Please use the WhatsApp button or call us.", "err");
      } catch { say("Sorry, the enquiry could not be sent. Please use the WhatsApp button or call us.", "err"); }
      btn.disabled = false;
    });
    const started = $("[name=started]", form); if (started) started.value = Date.now();
    if (new URLSearchParams(location.search).get("error")) say("Sorry, the enquiry could not be sent. Please check the form, or use the WhatsApp button or call us.", "err");
    const date = $("[name=date]", form); if (date) date.min = new Date().toISOString().slice(0, 10);
  });

  /* floating WhatsApp button hides while the home hero (which has its own buttons) is on screen */
  const wa = $(".wa"), stage = $("#stage");
  if (wa && stage && "IntersectionObserver" in window) new IntersectionObserver(e => wa.classList.toggle("off", e[0].isIntersecting), { threshold: .35 }).observe(stage);

  const yr = $("#year"); if (yr) yr.textContent = new Date().getFullYear();
})();
