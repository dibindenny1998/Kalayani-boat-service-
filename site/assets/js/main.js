/* Kalyani Boat Service: shared behaviour for every page.
   Tour data and contact numbers come from assets/js/data.js (generated by build/build.py). */
(() => {
  const K = window.KALYANI;
  const still = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => [...r.querySelectorAll(s)];
  const inr = v => "₹" + v.toLocaleString("en-IN");
  const waLink = msg => "https://wa.me/" + K.whatsapp + "?text=" + encodeURIComponent(msg);

  /* mobile menu */
  const menu = $(".menu"), nav = $(".nav");
  if (menu) {
    const set = o => { nav.classList.toggle("open", o); menu.setAttribute("aria-expanded", o); };
    menu.onclick = () => set(!nav.classList.contains("open"));
    nav.addEventListener("click", e => { if (e.target.closest("a")) set(false); });
    document.addEventListener("click", e => { if (!e.target.closest(".bar")) set(false); });
  }

  /* Google Analytics events: WhatsApp, call, email, map and review clicks (no personal details are sent) */
  const track = (name, params) => { if (typeof window.gtag === "function") window.gtag("event", name, params || {}); };
  document.addEventListener("click", e => {
    const a = e.target.closest("a"); if (!a) return;
    const h = a.getAttribute("href") || "";
    const where = a.closest(".top") ? "header" : a.closest(".hero") ? "hero" : a.closest(".dock, .fab") ? "sticky_bar" : a.closest(".foot") ? "footer" : "page";
    const page = location.pathname.replace(/^\//, "") || "index.html";
    if (a.hasAttribute("data-wa") || h.includes("wa.me")) track("whatsapp_click", { link_location: where, page });
    else if (h.startsWith("tel:")) track("phone_click", { link_location: where, page });
    else if (h.startsWith("mailto:")) track("email_click", { link_location: where, page });
    else if (/maps\.app|google\.com\/maps/.test(h)) track("map_click", { page });
    else if (/tripadvisor|g\.co\/kgs/.test(h)) track("review_link_click", { platform: h.includes("tripadvisor") ? "tripadvisor" : "google" });
  }, true);

  /* every [data-wa] link opens WhatsApp with its own message */
  $$("[data-wa]").forEach(a => { a.href = waLink(a.dataset.wa); a.target = "_blank"; a.rel = "noopener"; });

  /* reveals: anything on screen shows at once, the rest fades up on scroll */
  const rv = $$(".rv");
  if (still || !("IntersectionObserver" in window)) rv.forEach(e => e.classList.add("in"));
  else {
    const io = new IntersectionObserver(es => es.forEach(e => { if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); } }), { threshold: 0, rootMargin: "0px 0px 15% 0px" });
    rv.forEach((e, i) => { if (e.getBoundingClientRect().top < innerHeight) setTimeout(() => e.classList.add("in"), 80 * (i % 6)); else io.observe(e); });
  }

  /* tours: filter by time of day */
  $$(".filters").forEach(f => {
    const rail = f.nextElementSibling;
    f.addEventListener("click", e => {
      const b = e.target.closest(".filter"); if (!b) return;
      $$(".filter", f).forEach(x => x.classList.toggle("on", x === b));
      $$(".card, figure", rail).forEach(c => { c.hidden = !(b.dataset.f === "all" || c.dataset.part === b.dataset.f); if (!c.hidden) c.classList.add("in"); });
      if (rail.classList.contains("rail")) rail.scrollTo({ left: 0, behavior: still ? "auto" : "smooth" });
    });
  });

  /* contact map: load Google Maps only when asked */
  $$("[data-showmap]").forEach(b => b.addEventListener("click", () => {
    const box = b.closest("[data-map]"), f = document.createElement("iframe");
    f.src = box.dataset.map; f.title = "Map to Rajiv Boat Jetty"; f.loading = "lazy"; f.referrerPolicy = "no-referrer-when-downgrade";
    box.innerHTML = ""; box.appendChild(f); box.classList.add("on");
  }));

  /* rails can be dragged with a mouse */
  $$(".rail").forEach(r => {
    let down = false, x0 = 0, s0 = 0, moved = false;
    r.addEventListener("pointerdown", e => { if (e.pointerType !== "mouse") return; down = true; moved = false; x0 = e.clientX; s0 = r.scrollLeft; });
    addEventListener("pointermove", e => { if (!down) return; const dx = e.clientX - x0; if (Math.abs(dx) > 4) { moved = true; r.classList.add("drag"); } r.scrollLeft = s0 - dx; });
    addEventListener("pointerup", () => { down = false; r.classList.remove("drag"); });
    r.addEventListener("click", e => { if (moved) { e.preventDefault(); moved = false; } }, true);
  });

  /* sunrise / sunset compare: sweeps on its own until someone drags it */
  const cmp = $("#compare");
  if (cmp) {
    const input = $("input", cmp); let touched = false; const t0 = performance.now();
    const set = v => cmp.style.setProperty("--c", v + "%");
    input.addEventListener("input", () => { touched = true; set(input.value); });
    const sweep = n => { if (touched) return; const v = 50 + 30 * Math.sin((n - t0) / 1800); set(v.toFixed(1)); input.value = v; requestAnimationFrame(sweep); };
    if (!still && "IntersectionObserver" in window) { let running = false; new IntersectionObserver(e => { if (e[0].isIntersecting && !running) { running = true; requestAnimationFrame(sweep); } }).observe(cmp); }
  }

  /* route line draws as it scrolls into view */
  $$(".route").forEach(r => {
    if (still) return;
    const draw = () => { const b = r.getBoundingClientRect(); r.style.setProperty("--p", Math.min(1, Math.max(0, (innerHeight * .85 - b.top) / b.height)).toFixed(3)); };
    addEventListener("scroll", draw, { passive: true }); draw();
  });

  /* booking: price for two, plus each extra guest per hour */
  const rate = (t, food) => (food && t.extra_food) ? t.extra_food : t.extra;
  const price = (t, g, food) => t.price + Math.max(0, g - 2) * rate(t, food) * t.hours;
  $$("[data-calc]").forEach(form => {
    const sel = $("[name=tour]", form), out = $("output", form), sum = $(".sum", form), note = $(".sumnote", form), date = $("[name=date]", form);
    let guests = 2, shown = 0, raf;
    const ride = () => K.rides.find(r => r.slug === sel.value);
    const foodField = $("[data-foodfield]", form), foodSel = foodField && $("select", foodField);
    const withFood = () => !!(foodSel && foodSel.value === "1" && tour().extra_food);
    const tour = () => K.tours.find(t => t.slug === sel.value) || K.tours[0];
    const update = () => {
      const r = ride();
      if (r) {
        if (foodField) foodField.hidden = true;
        out.value = guests; out.textContent = guests; $("[name=guests]", form).value = guests;
        cancelAnimationFrame(raf); shown = 0; sum.textContent = "On request"; note.textContent = "We reply with the rate and timings for " + r.name.toLowerCase() + ".";
        return;
      }
      const t = tour(), food = withFood(), v = price(t, guests, food), extra = Math.max(0, guests - 2);
      if (foodField) foodField.hidden = !(t.extra_food && extra);
      out.value = guests; out.textContent = guests; $("[name=guests]", form).value = guests;
      note.textContent = extra ? `${inr(t.price)} for two + ${extra} × ₹${rate(t, food)} × ${t.hours} hours${food ? " (with food)" : ""}` : "Price for two guests";
      cancelAnimationFrame(raf);
      if (still || !shown) { shown = v; sum.textContent = inr(v); return; }
      const from = shown, st = performance.now();
      const step = n => { const k = Math.min(1, (n - st) / 500), e = 1 - Math.pow(1 - k, 3); shown = Math.round(from + (v - from) * e); sum.textContent = inr(shown); if (k < 1) raf = requestAnimationFrame(step); };
      raf = requestAnimationFrame(step);
    };
    $("[data-step='-1']", form).onclick = () => { if (guests > 1) { guests--; update(); } };
    $("[data-step='1']", form).onclick = () => { if (guests < 30) { guests++; update(); } };
    sel.addEventListener("change", update);
    if (foodSel) foodSel.addEventListener("change", update);
    const want = new URLSearchParams(location.search).get("tour");
    if (want && (K.tours.some(t => t.slug === want) || K.rides.some(r => r.slug === want))) sel.value = want;
    date.min = new Date().toISOString().slice(0, 10);
    update();

    const status = $(".status", form);
    const say = (msg, kind) => { status.hidden = false; status.className = "status " + (kind || ""); status.textContent = msg; };
    const summary = () => {
      const f = new FormData(form), r = ride(), t = tour();
      if (r) return [`Hi Kalyani Boat Service! I'd like to enquire about ${r.name.toLowerCase()}:`, f.get("date") ? `Date: ${f.get("date")}` : "", `Guests: ${guests}`, "Please share the rate and timings.", f.get("name") ? `Name: ${f.get("name")}` : "", f.get("phone") ? `Phone: ${f.get("phone")}` : "", f.get("message") ? `Note: ${f.get("message")}` : ""].filter(Boolean).join("\n");
      return [`Hi Kalyani Boat Service! I'd like to book:`, `Tour: ${t.name} (${t.time})`, f.get("date") ? `Date: ${f.get("date")}` : "", `Guests: ${guests}`,
        `Price shown: ${inr(price(t, guests, withFood()))}${guests > 2 && withFood() ? " (extra guests with food)" : ""}`, f.get("name") ? `Name: ${f.get("name")}` : "", f.get("phone") ? `Phone: ${f.get("phone")}` : "", f.get("message") ? `Note: ${f.get("message")}` : ""].filter(Boolean).join("\n");
    };
    const lead = method => { const r = ride(), t = tour(); track("generate_lead", r ? { method, tour: r.slug, guests } : { method, tour: t.slug, guests, value: price(t, guests, withFood()), currency: "INR" }); };
    $("[data-send=wa]", form).onclick = () => { lead("whatsapp_form"); window.open(waLink(summary()), "_blank", "noopener"); };
    const mailBtn = $("[data-send=mail]", form);
    if (mailBtn) mailBtn.onclick = () => { lead("email_app"); location.href = "mailto:" + K.email + "?subject=" + encodeURIComponent("Shikara booking enquiry") + "&body=" + encodeURIComponent(summary()); };
    form.addEventListener("submit", async e => {
      e.preventDefault();
      if (!form.reportValidity()) return;
      const btn = $("[type=submit]", form); btn.disabled = true; say("Sending…");
      try {
        const res = await fetch(form.action, { method: "POST", body: new FormData(form), headers: { Accept: "application/json" } });
        const data = await res.json().catch(() => ({}));
        if (res.ok && data.ok) { lead("email_form"); say("Request sent. We will confirm on WhatsApp or by phone.", "ok"); form.reset(); guests = 2; update(); }
        else say(data.error || "Sorry, that did not go through. Please use WhatsApp or call us.", "err");
      } catch { say("Sorry, that did not go through. Please use WhatsApp or call us.", "err"); }
      btn.disabled = false;
    });
    $("[name=started]", form).value = Date.now();
    if (new URLSearchParams(location.search).get("error")) say("Sorry, that did not go through. Please check the form, or use WhatsApp.", "err");
  });

  /* floating chat and mail buttons hide over the home hero */
  const fab = $("#fab");
  if (fab && "IntersectionObserver" in window) {
    const over = new Set();
    const watch = new IntersectionObserver(es => { es.forEach(e => e.isIntersecting ? over.add(e.target) : over.delete(e.target)); fab.classList.toggle("off", over.size > 0); }, { threshold: .05 });
    [$("#hero"), ...$$("[data-calc]"), $(".foot")].filter(Boolean).forEach(el => watch.observe(el));
  }

  /* mobile booking dock: hidden over the home hero and the footer */
  const dock = $("#dock"), hero = $("#hero"), foot = $(".foot");
  if (dock && "IntersectionObserver" in window) {
    const seen = new Set();
    const io = new IntersectionObserver(es => { es.forEach(e => e.isIntersecting ? seen.add(e.target) : seen.delete(e.target)); dock.classList.toggle("off", seen.size > 0); }, { threshold: .15 });
    [hero, foot, ...$$("[data-calc]")].filter(Boolean).forEach(el => io.observe(el));
  }
  const yr = $("#year"); if (yr) yr.textContent = new Date().getFullYear();
})();
